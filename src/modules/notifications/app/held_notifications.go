type HeldInput struct {
	GymID, ID, ActorID uuid.UUID
	Version            int
	Action             string
}
type HeldView struct {
	ID          uuid.UUID `json:"id"`
	Version     int       `json:"version"`
	Recipient   string    `json:"recipient"`
	TemplateKey string    `json:"template_key"`
	Channel     string    `json:"channel"`
	CreatedAt   time.Time `json:"created_at"`
	Reason      *string   `json:"reason"`
	Blocked     string    `json:"blocked"`
}
type HeldNotifications struct {
	Gyms          gymRepo.GymRepository
	Notifications repo.NotificationRepository
	Held          repo.HeldRepository
	Templates     repo.TemplateOverrideRepository
	OptOut        repo.OptOutRepository
	UoW           shared.UnitOfWork
	Audit         audit.Recorder
	// Zero leaves cleanup disabled until the retention policy is approved.
	RetentionDays int
}

func NewHeldNotifications(nr repo.NotificationRepository, hr repo.HeldRepository, t repo.TemplateOverrideRepository, o repo.OptOutRepository, u shared.UnitOfWork, a audit.Recorder) *HeldNotifications {
	return &HeldNotifications{Notifications: nr, Held: hr, Templates: t, OptOut: o, UoW: u, Audit: a}
}

// An allowlist keeps old credentials, expiring payment links and time-relative
// reminders out of recovery. Generate those again in their original flow.
var recoveryLink = regexp.MustCompile(`(?i)(www\.|[a-z0-9-]+\.(com|app|mx|org|net|io|co)(/|\b))`)

func recoveryContentBlock(msg *n.Notification) string {
	if strings.HasPrefix(msg.TemplateKey, "receipt_") && msg.Channel != n.ChannelWhatsApp {
		return "Genera un comprobante nuevo desde Pagos para enviarlo por correo."
	}
	switch msg.TemplateKey {
	case "receipt_membership", "receipt_product", "member_welcome_number", "broadcast_freeform":
	default:
		return "Este aviso puede haber vencido. Genéralo de nuevo desde su sección."
	}
	if tpl.LookupDefault(msg.TemplateKey) == nil {
		return "Esta plantilla ya no está disponible."
	}
	if msg.Channel != n.ChannelWhatsApp && msg.Channel != n.ChannelEmail {
		return "Este mensaje no admite envío."
	}
	for key, value := range msg.Payload {
		k := strings.ToLower(key)
		v := strings.ToLower(value)
		if k == "receipt_url" && strings.HasPrefix(msg.TemplateKey, "receipt_") {
			continue
		} // regenerated by dispatcher
		if strings.Contains(k, "token") || strings.Contains(k, "password") || k == "pin" || k == "code" || strings.Contains(k, "url") || strings.Contains(v, "http:") || strings.Contains(v, "https:") || recoveryLink.MatchString(v) {
			return "Este mensaje contiene un enlace o una credencial. Genéralo de nuevo desde su sección."
		}
	}
	return ""
}
func (uc *HeldNotifications) Validate(tx shared.Transaction, msg *n.Notification) (string, error) {
	if uc.Gyms != nil {
		g, err := uc.Gyms.GetByID(tx, msg.GymID)
		if err != nil {
			return "", err
		}
		if !g.CanAccessFeature(gymDomain.FeatureHeldMessages) {
			return "Tu plan actual no incluye la recuperación de mensajes.", nil
		}
	}
	if reason := recoveryContentBlock(msg); reason != "" {
		return reason, nil
	}
	reason, err := uc.Held.RecoveryRecipient(tx, msg)
	if err != nil || reason != "" {
		return reason, err
	}
	override, err := uc.Templates.GetByGymAndKey(tx, msg.GymID, msg.TemplateKey)
	if err != nil {
		return "", err
	}
	if override != nil && !override.Enabled {
		return "Esta plantilla está desactivada.", nil
	}
	if isMarketingTemplate(msg.TemplateKey) {
		if uc.OptOut == nil {
			return "No se pudo comprobar el permiso del destinatario.", nil
		}
		opted, err := uc.OptOut.IsOptedOut(tx, msg.RecipientAddress)
		if err != nil {
			return "", err
		}
		if opted {
			return "El destinatario pidió no recibir estos mensajes.", nil
		}
	}
	return "", nil
}
func (uc *HeldNotifications) List(ctx context.Context, gym uuid.UUID, page int) ([]HeldView, int, error) {
	if page < 1 {
		page = 1
	}
	tx, err := uc.UoW.Query(ctx)
	defer shared.CloseQuery(tx)
	if err != nil {
		return nil, 0, err
	}
	rows, total, err := uc.Notifications.ListByGym(tx, gym, n.StatusHeld, page, 20)
	if err != nil {
		return nil, 0, err
	}
	views := make([]HeldView, 0, len(rows))
	for _, msg := range rows {
		block, err := uc.Validate(tx, msg)
		if err != nil {
			return nil, 0, err
		}
		views = append(views, HeldView{msg.ID, msg.Version, msg.RecipientAddress, msg.TemplateKey, msg.Channel, msg.CreatedAt, msg.ErrorMessage, block})
	}
	return views, total, nil
}
func (uc *HeldNotifications) Execute(ctx context.Context, in HeldInput) (string, error) {
	if in.Version < 1 || (in.Action != "send" && in.Action != "discard") {
		return "", shared.NewValidationError(errors.New("Elige enviar o descartar el mensaje."))
	}
	result := "queued"
	if in.Action == "discard" {
		result = "discarded"
	}
	err := uc.UoW.Command(ctx, func(tx shared.Transaction) error {
		msg, err := uc.Held.LockHeld(tx, in.GymID, in.ID)
		if err != nil {
			return err
		}
		if msg == nil {
			return shared.NewBusinessError(notiErrors.ErrHeldConflict, "")
		}
		if msg.RecoveryVersion == in.Version && msg.RecoveryAction == in.Action {
			return nil
		}
		if msg.Status != n.StatusHeld || msg.Version != in.Version || msg.DeletedAt != nil {
			return shared.NewBusinessError(notiErrors.ErrHeldConflict, "")
		}
		if in.Action == "send" {
			block, err := uc.Validate(tx, msg)
			if err != nil {
				return err
			}
			if block != "" {
				return shared.NewBusinessError(errors.New(block), "")
			}
		}
		now := time.Now().UTC()
		reason := msg.ErrorMessage
		msg.ResolveHeld(in.Version, in.Action, now)
		if _, err = uc.Notifications.Update(tx, msg); err != nil {
			return err
		}
		return uc.Audit.Record(ctx, tx, audit.Entry{GymID: in.GymID, EntityType: "notification_queue", EntityID: in.ID, Action: "held_" + in.Action, ActorUserID: &in.ActorID, Changes: map[string]any{"reason": reason, "version": in.Version, "template_key": msg.TemplateKey}, At: now})
	})
	return result, err
}
func (uc *HeldNotifications) Cleanup(ctx context.Context, now time.Time) (int, error) {
	if uc.RetentionDays <= 0 {
		return 0, nil
	}
	total := 0
	err := uc.UoW.Command(ctx, func(tx shared.Transaction) error {
		rows, err := uc.Held.OldHeld(tx, now.AddDate(0, 0, -uc.RetentionDays), 100)
		if err != nil {
			return err
		}
		for _, msg := range rows {
			msg.ResolveHeld(msg.Version, "discard", now)
			msg.DeletedAt = &now
			if _, err = uc.Notifications.Update(tx, msg); err != nil {
				return err
			}
			if err = uc.Audit.Record(ctx, tx, audit.Entry{GymID: msg.GymID, EntityType: "notification_queue", EntityID: msg.ID, Action: "held_archived", Changes: map[string]any{"retention_days": uc.RetentionDays}, At: now}); err != nil {
				return err
			}
			total++
		}
		return nil
	})
	return total, err
}
